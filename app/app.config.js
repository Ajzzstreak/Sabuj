// The app's name / slug / scheme / bundle id live in app.identity.json and
// nowhere else. This file and src/config.ts both read from it, so renaming
// the product is a one-file change.
const identity = require('./app.identity.json');

// Accent from src/theme/tokens.ts (light palette).
const ACCENT = '#5B43F0';
// Splash backgrounds match palettes.light.bg / palettes.dark.bg.
const SPLASH_LIGHT = '#F5F4F1';
const SPLASH_DARK = '#09090B';

const CAMERA_PERMISSION = `${identity.name} uses the camera only to scan product barcodes, so it can look up prices. No photos or video are saved.`;

/**
 * iOS privacy manifest (PrivacyInfo.xcprivacy).
 *
 * Required-reason APIs: the union of what the installed native modules declare in
 * their own PrivacyInfo.xcprivacy (checked in node_modules for SDK 58):
 *   react-native (React, cxxreact)         FileTimestamp C617.1, UserDefaults CA92.1
 *   react-native (react/timing)            SystemBootTime 35F9.1
 *   @react-native-async-storage            FileTimestamp C617.1
 *   expo-application                       FileTimestamp C617.1
 *   expo-constants, expo-notifications,
 *   expo-system-ui                         UserDefaults CA92.1
 *   expo-file-system (via expo)            FileTimestamp 0A2A.1 3B52.1, DiskSpace E174.1 85F4.1
 * Re-check after adding or upgrading a native module.
 *
 * Collected data: what the app sends to its own server (see app/store/PRIVACY_ANSWERS.md).
 * Nothing is used for tracking, no ads SDK, no third-party analytics.
 */
const purpose = (...p) => p.map((x) => `NSPrivacyCollectedDataTypePurpose${x}`);
const collected = (type, purposes) => ({
  NSPrivacyCollectedDataType: `NSPrivacyCollectedDataType${type}`,
  // Linked: stored on the server against the anonymous install id.
  NSPrivacyCollectedDataTypeLinked: true,
  NSPrivacyCollectedDataTypeTracking: false,
  NSPrivacyCollectedDataTypePurposes: purposes,
});
const privacyManifests = {
  NSPrivacyTracking: false,
  NSPrivacyTrackingDomains: [],
  NSPrivacyAccessedAPITypes: [
    { NSPrivacyAccessedAPIType: 'NSPrivacyAccessedAPICategoryFileTimestamp', NSPrivacyAccessedAPITypeReasons: ['C617.1', '0A2A.1', '3B52.1'] },
    { NSPrivacyAccessedAPIType: 'NSPrivacyAccessedAPICategoryUserDefaults', NSPrivacyAccessedAPITypeReasons: ['CA92.1'] },
    { NSPrivacyAccessedAPIType: 'NSPrivacyAccessedAPICategorySystemBootTime', NSPrivacyAccessedAPITypeReasons: ['35F9.1'] },
    { NSPrivacyAccessedAPIType: 'NSPrivacyAccessedAPICategoryDiskSpace', NSPrivacyAccessedAPITypeReasons: ['E174.1', '85F4.1'] },
  ],
  NSPrivacyCollectedDataTypes: [
    // Anonymous install id / bearer token and the Expo push token.
    collected('DeviceID', purpose('AppFunctionality')),
    // Searches and "Ask" questions.
    collected('SearchHistory', purpose('AppFunctionality', 'ProductPersonalization')),
    // Product views, store taps, saves, list adds/removes, price alerts.
    collected('ProductInteraction', purpose('AppFunctionality', 'ProductPersonalization')),
    // ZIP code (entered by the user, never GPS).
    collected('CoarseLocation', purpose('AppFunctionality')),
    // Store memberships (Costco / Sam's Club) and chosen stores.
    collected('OtherDataTypes', purpose('AppFunctionality', 'ProductPersonalization')),
  ],
};

