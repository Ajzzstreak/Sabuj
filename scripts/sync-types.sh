#!/usr/bin/env bash
# Copies the canonical API contract into each package that consumes it.
set -euo pipefail
root="$(cd "$(dirname "$0")/.." && pwd)"
for dest in server/src/contract.ts app/src/api/contract.ts; do
  mkdir -p "$(dirname "$root/$dest")"
  { echo "// GENERATED by scripts/sync-types.sh from shared/types.ts — do not edit."; cat "$root/shared/types.ts"; } > "$root/$dest"
done
echo "contract synced"
