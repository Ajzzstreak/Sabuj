#!/usr/bin/env bash
# Copies the canonical API contract into each package that consumes it.
#   scripts/sync-types.sh          write the copies
#   scripts/sync-types.sh --check  write nothing; exit 1 if a copy differs from shared/types.ts (CI)
set -euo pipefail
root="$(cd "$(dirname "$0")/.." && pwd)"
header="// GENERATED by scripts/sync-types.sh from shared/types.ts — do not edit."
check=0
[[ "${1:-}" == "--check" ]] && check=1
stale=0
for dest in server/src/contract.ts app/src/api/contract.ts; do
  if [[ $check == 1 ]]; then
    if ! diff -q <({ echo "$header"; cat "$root/shared/types.ts"; }) "$root/$dest" >/dev/null 2>&1; then
      echo "contract out of sync: $dest differs from shared/types.ts (run scripts/sync-types.sh)" >&2
      stale=1
    fi
  else
    mkdir -p "$(dirname "$root/$dest")"
    { echo "$header"; cat "$root/shared/types.ts"; } > "$root/$dest"
  fi
done
if [[ $check == 1 ]]; then
  [[ $stale == 0 ]] && echo "contract in sync"
  exit $stale
fi
echo "contract synced"
